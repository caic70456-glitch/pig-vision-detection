def table(doc, rows, widths, size=10, header=True):
    n = len(rows[0])
    if len(widths) != n:
        raise ValueError(f"widths {len(widths)} != cols {n}")
    for ri, r in enumerate(rows):
        if len(r) != n:
            raise ValueError(f"row {ri} has {len(r)} cols")
    t = doc.add_table(rows=0, cols=n)
    t.style = "Table Grid"
    t.autofit = False
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    tblPr = t._tbl.tblPr
    tblPr.append(tblPr.makeelement(qn("w:tblW"), {qn("w:type"): "pct", qn("w:w"): "5000"}))
    tblPr.append(tblPr.makeelement(qn("w:tblLayout"), {qn("w:type"): "fixed"}))
    grid = t._tbl.find(qn("w:tblGrid"))
    for gc, w in zip(grid.findall(qn("w:gridCol")), widths):
        gc.set(qn("w:w"), str(int(round(w * 567))))
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, v in enumerate(row):
            cells[ci].width = Cm(widths[ci])
            p = cells[ci].paragraphs[0]
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.line_spacing = 1.0
            add_rich(p, str(v), size=size, base_bold=(header and ri == 0))
    return t


