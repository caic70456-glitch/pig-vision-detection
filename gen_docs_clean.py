def set_run(run, size=12, bold=False, font=BODY, color=None):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = font
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font)
    if color:
        run.font.color.rgb = color


def add_rich(p, text, size=12, base_bold=False, font=BODY, color=None):
    """写入文本并解析 **加粗** 标记，生成真正的加粗 run（不留符号）。"""
    text = text.replace("`", "")
    parts = re.split(r"\*\*(.+?)\*\*", text, flags=re.S)
    for i, seg in enumerate(parts):
        if not seg:
            continue
        set_run(p.add_run(seg), size=size,
                bold=base_bold or (i % 2 == 1), font=font, color=color)


def para(doc, text="", size=12, bold=False, font=BODY, align=None,
         first_indent=True, space_after=6, line_spacing=1.0, color=None):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = line_spacing
    if first_indent:
        pf.first_line_indent = Pt(size * 2)
    if text:
        add_rich(p, text, size=size, base_bold=bold, font=font, color=color)
    return p


